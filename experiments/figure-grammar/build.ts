/**
 * node build.ts
 * Renders the three figures and writes out/index.html, the comparison page.
 * Inputs: figures/*.ts (the data) and, for the hand-built side of the comparison,
 * D's index.html, from which Figures 1 and 2 are copied verbatim.
 * Deterministic: no clock, no randomness beyond the seeded jitter in render.ts.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { render } from "./render.ts";
import { fig1 } from "./figures/fig1.ts";
import { fig2 } from "./figures/fig2.ts";
import { fig3 } from "./figures/fig3.ts";

const here = (p: string) => fileURLToPath(new URL(p, import.meta.url));
const DATE = "2026-10-14"; // the sheet date, fixed so a rebuild is byte-identical
const dHtml = readFileSync(here("../identity-specimens/d-drawn/index.html"), "utf8");

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** Copy one element from D's page by its opening tag, matching nested tags of the same name. */
function extract(open: string, tag: string): string {
  const start = dHtml.indexOf(open);
  if (start < 0) throw new Error(`D's index.html has no ${open}`);
  const re = new RegExp(`<${tag}[\\s>]|</${tag}>`, "g");
  re.lastIndex = start;
  let depth = 0;
  for (let m = re.exec(dHtml); m; m = re.exec(dHtml)) {
    depth += m[0].startsWith("</") ? -1 : 1;
    if (depth === 0) return dHtml.slice(start, m.index + m[0].length);
  }
  throw new Error(`unclosed ${open}`);
}

/** Comparison page only: show both orientations, each under a mono label. */
const labelOrientations = (html: string) =>
  html.replace(/(<svg class="fig-(wide|narrow)"[\s\S]*?<\/svg>)/g, '<div class="orient orient-$2">\n<p class="orient-label">$2</p>\n$1\n</div>');

const r1 = render(fig1), r2 = render(fig2), r3 = render(fig3);

const handBuilt = (n: 1 | 2) => [
  labelOrientations(extract(`<figure class="fig fig-${n}"`, "figure")),
  // D's text equivalent, so the copied SVGs' aria-describedby still resolves
  `<div class="fig-detail">`,
  extract(`<p id="fig${n}-equivalent"`, "p"),
  `</div>`,
].join("\n");

const rendered = (r: ReturnType<typeof render>) => labelOrientations(r.figure);

const sheet = (no: string, label: string, id: string, title: string, body: string) => `
    <section class="sheet sheet-figure" aria-labelledby="${id}">
      <div class="sheet-margin"><span class="sheet-no">${no}</span><span class="sheet-label">${label}</span></div>
      <div class="sheet-body">
        <h2 id="${id}">${title}</h2>
      </div>
      <div class="cmp">
${body}
      </div>
    </section>`;

const pair = (n: 1 | 2, r: ReturnType<typeof render>, file: string) => `
<h3 class="cmp-head">Hand-built <span class="cmp-src">identity-specimens/d-drawn/index.html</span></h3>
${handBuilt(n)}
<h3 class="cmp-head">Rendered <span class="cmp-src">${file}</span></h3>
${rendered(r)}`;

const dataFile = (file: string) =>
  `<h3 class="cmp-head"><span class="cmp-src">${file}</span></h3>\n<pre class="data"><code>${esc(readFileSync(here(file), "utf8"))}</code></pre>`;

const page = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Figure grammar, experiment 2, clean.dev</title>
  <!-- Generated by build.ts. Do not edit; edit figures/*.ts or render.ts and run node build.ts. -->
  <!-- TEMPORARY (specimen only): IBM Plex from Google Fonts, as in D. Repo fonts are fallbacks in D's styles.css. -->
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;600&family=IBM+Plex+Sans:ital,wght@0,400;0,600;1,400&display=swap">
  <link rel="stylesheet" href="../../identity-specimens/d-drawn/styles.css">
  <link rel="stylesheet" href="compare.css">
</head>
<body class="compare">
  <a class="skip" href="#main">Skip to content</a>

  <header class="tb tb-nonav" aria-label="Title block">
    <div class="tb-brand">
      <span class="tb-label">Project</span>
      <a class="tb-name" href="/" aria-label="clean.dev, home">clean.dev</a>
    </div>
    <div class="tb-meta"><p class="tb-cell tb-sheet"><span class="tb-label">Sheet</span> <span class="tb-value">Figure grammar</span></p><p class="tb-cell tb-rev"><span class="tb-label">Rev.</span> <span class="tb-value">experiment 2</span></p><p class="tb-cell tb-date"><span class="tb-label">Date</span> <span class="tb-value"><time datetime="${DATE}">${DATE}</time></span></p><p class="tb-cell tb-drawn"><span class="tb-label">Drawn by</span> <span class="tb-value">Martin Trenker with a coding agent</span></p><div class="tb-cell tb-lang"><span class="tb-label" id="lang-label">Lang.</span> <span class="tb-value" role="group" aria-labelledby="lang-label"><a href="/" aria-current="page" lang="en">EN</a><span class="tb-slash" aria-hidden="true"> / </span><a href="/de/" lang="de" hreflang="de">DE</a></span>
      </div>
    </div>
  </header>

  <main id="main" tabindex="-1">
${sheet("01", "Fig. 1", "s-fig1", "Where the work waits", pair(1, r1, "figures/fig1.ts"))}
${sheet("02", "Fig. 2", "s-fig2", "Two ways to work with agents", pair(2, r2, "figures/fig2.ts"))}
${sheet("03", "Fig. 3", "s-fig3", "The bottleneck moves", `<h3 class="cmp-head">Rendered <span class="cmp-src">figures/fig3.ts</span></h3>\n${rendered(r3)}`)}
${sheet("04", "Data", "s-data", "Data", ["figures/fig1.ts", "figures/fig2.ts", "figures/fig3.ts"].map(dataFile).join("\n"))}
  </main>

  <footer class="foot">
    <p class="foot-line">Open source and built in public.</p>
    <ul class="foot-links">
      <li><a href="https://github.com/mtrenker/clean.dev">GitHub</a></li>
    </ul>
    <p class="colophon">Generated by build.ts from the figure data. The hand-built figures are copied from direction D.</p>
  </footer>
  <script type="module" src="../live.js"></script>
</body>
</html>
`;

mkdirSync(here("out"), { recursive: true });
writeFileSync(here("out/index.html"), page);
console.log("wrote out/index.html");
